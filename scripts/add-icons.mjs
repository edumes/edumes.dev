// Vendors animated icons from lucide-animated.com (MIT) into src/components/icons and rebuilds the index <Icon> reads.
// Usage: npm run icons:add -- github arrow-right
// Patched on the way in: a <span> wrapper (valid inside <p> and <button>) and the site's 1.75 stroke.
import fs from 'node:fs';

const dir = 'src/components/icons';
fs.mkdirSync(dir, { recursive: true });

for (const name of process.argv.slice(2)) {
  const res = await fetch(`https://lucide-animated.com/r/${name}.json`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const src = (await res.json()).files[0].content
    .replaceAll('HTMLDivElement', 'HTMLSpanElement')
    .replaceAll('<div', '<span')
    .replaceAll('</div>', '</span>')
    .replaceAll('strokeWidth="2"', 'strokeWidth="1.75"');
  if (src.includes('<div')) throw new Error(`${name}: unexpected markup, patch it by hand`);
  fs.writeFileSync(`${dir}/${name}.tsx`, src);
}

const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.tsx'))
  .sort()
  .map((f) => [f.slice(0, -4), fs.readFileSync(`${dir}/${f}`, 'utf8').match(/export \{ (?:\w+ as )?(\w+) \}/)[1]]);
fs.writeFileSync(
  `${dir}/index.ts`,
  `// Generated by scripts/add-icons.mjs.\n${entries.map(([f, c]) => `import { ${c} } from './${f}';`).join('\n')}\n\nexport const icons = {\n${entries.map(([f, c]) => `  '${f}': ${c},`).join('\n')}\n};\n`
);
